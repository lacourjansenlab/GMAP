"""
This file automatically compares the outputs generated using AIM with
the current GMAP version. GMAP creates the outputs live while this file
is run, so it always compares the most recent version of GMAP with AIM
outputs.

The purpose of this comparison is to see/check that the outputs
generated by GMAP are (most likely!) correct. During development,
frequencies didn't match, and we could observe how large the differences
were. Wrongly-calculated frequencies had always a frequency that
differed by at least 0.1 cm-1.

We cannot be more strict in comparing values as we currently are, as we
would then be detecting float errors (both programs use float32s).
The observant would notice that not all frequencies are compared equally
strictly. The chosen limits are the closest that worked while developing
the tests. During development, both programs were altered such that
they showed how they arrived at the results, and the outcomes of
np.multiply(VEG found, map constants) were incredibly close. The fact
that some maps have larger errors is (most likely) due to how the
float errors (which mainly originate in electric
potential/field/gradient calculations) are propagated until the
frequency.
"""


