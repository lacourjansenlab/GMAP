@pytest.mark.nofiles
def core_test_frequencies(mapname, NNtreat, tmp_path, limit):
    # This runs GMAP to create the results
    curdir = Path(__file__).resolve().parent
    cmdpars = [
        "GMAP", "GEM", "run",
        str((curdir / "data/basic_parameters.txt").resolve()),
        "--AmideBB.frequency_map_choice", mapname,
        "--output_data", "ham\\;",
        "--output_directory", str(tmp_path.resolve()),
        "--log_directory", str(tmp_path.resolve())
    ]
    if NNtreat == "_noNN":
        cmdpars += ["--AmideBB.consider_nearest_neighbours", "False"]
    GM_ci.cmd_interface(cmdpars)

    # now, we must test these newly generated results against the
    # AIM-calculated frequencies to see if the map is indeed correct.
    hamnew = makeham((tmp_path / "hamiltonian.txt").resolve(), 128)
    fname = f"data/{mapname}-freq{NNtreat}_AIM_V1-0-2_Hamiltonian.txt"
    hamold = makeham((curdir / fname).resolve(), 128)

    # this way, if the two do not match, we automatically get printed where/why
    # they disagree.
    # The value of 0.0002 should be large enough to allow for float errors,
    # but small enough to catch everything else.
    assert bool(np.any(np.isnan(np.diag(hamnew)))) is False
    mismatch = np.where(np.abs(np.diag(hamold) - np.diag(hamnew)) > limit)[0]
    print(mismatch)
    print(np.diag(hamold)[mismatch])
    print(np.diag(hamnew)[mismatch])
    print(
        np.average(np.diag(hamold) - np.diag(hamnew)),
        np.average(np.abs(np.diag(hamold) - np.diag(hamnew)))
    )
    print((np.diag(hamold) - np.diag(hamnew))[mismatch])
    assert mismatch.shape == (0,)


def makeham(fname, n_singles):
    with open(fname, "r") as fhand:
        flatham = fhand.readline()
    flatham = flatham.split()
    # we have the final +1 as the frame number is still in front!
    if len(flatham) != (n_singles * (n_singles + 1)) / 2 + 1:
        raise ValueError(
            "warning! provided hamiltonian length doesn't match!")
    flatham = flatham[1:]
    squareham = np.zeros((n_singles, n_singles))
    squareham[np.triu_indices(n_singles, k=0)] = flatham
    squareham = squareham + squareham.T - np.diag(np.diag(squareham))
    return squareham


