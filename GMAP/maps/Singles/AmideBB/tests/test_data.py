def core_compare_dippos(oldfile, newfile, limit):
    mismatch = np.where((oldfile - newfile) > limit)
    assert bool(np.any(np.isnan(newfile))) is False
    print(mismatch)
    print(oldfile[mismatch[0], mismatch[1]])
    print(newfile[mismatch[0], mismatch[1]])
    assert mismatch[0].shape == (0,)


def read_dippos(fname, n_singles, n_cols):
    with open(fname, "r") as fhand:
        flatarr = fhand.readline()
    flatarr = flatarr.split()
    # we have the final +1 as the frame number is still in front!
    if len(flatarr) != (n_singles * n_cols) + 1:
        raise ValueError(
            "warning! provided file length doesn't match!")
    flatarr = np.array(flatarr[1:], dtype=np.float32)
    # we have to transpose, as the file lists all xs first, then al ys and zs.
    squarearr = flatarr.reshape((n_cols, n_singles)).T
    return squarearr
